#[account]
pub struct EmpheralMerkleTree {
    pub levels: u32,
    pub current_index: u32,
    pub tree_stopped: u64,
    pub merkle_roots: Vec<[u8; 32]>,
    pub owner: Pubkey,
}

pub const ROOT_HISTORY_SIZE: u32 = 60;

#[derive(Accounts)]
pub struct InitializeEmpheralMerkleTree<'info> {
    #[account(
        init,
        payer = payer,
        space = 8 + 4 + 4 + 8 + 4 + (32 * ROOT_HISTORY_SIZE as usize) + 32 // Base + fields + merkle roots + owner
    )]
    pub empheral_merkle_tree: Account<'info, EmpheralMerkleTree>,
    #[account(mut)]
    pub payer: Signer<'info>,
    pub system_program: Program<'info, System>,
}

#[derive(Accounts)]
pub struct InsertLeaf<'info> {
    #[account(
        mut,
        constraint = empheral_merkle_tree.owner == payer.key()
    )]
    pub empheral_merkle_tree: Account<'info, EmpheralMerkleTree>,
    pub payer: Signer<'info>,
}

#[derive(Accounts)]
pub struct StopTree<'info> {
    #[account(
        mut,
        constraint = empheral_merkle_tree.owner == payer.key()
    )]
    pub empheral_merkle_tree: Account<'info, EmpheralMerkleTree>,
    pub payer: Signer<'info>,
}

#[derive(Accounts)]
pub struct IsKnownValueRoot<'info> {
    pub empheral_merkle_tree: Account<'info, EmpheralMerkleTree>,
}

#[derive(Accounts)]
pub struct GetLastMerkleRoot<'info> {
    pub empheral_merkle_tree: Account<'info, EmpheralMerkleTree>,
}

#[program]
pub mod merkle_tree {
    use super::*;

    pub fn initialize_empheral_merkle_tree(
        ctx: Context<InitializeEmpheralMerkleTree>,
        levels: u32,
    ) -> Result<()> {
        let empheral_merkle_tree = &mut ctx.accounts.empheral_merkle_tree;
        empheral_merkle_tree.levels = levels;
        empheral_merkle_tree.current_index = 0;
        empheral_merkle_tree.tree_stopped = 0;
        empheral_merkle_tree.owner = ctx.accounts.payer.key();
        
        // Initialize with zero merkle roots
        empheral_merkle_tree.merkle_roots = vec![[0u8; 32]; ROOT_HISTORY_SIZE as usize];
        empheral_merkle_tree.merkle_roots[0] = zeros(levels);
        
        Ok(())
    }

    pub fn insert_leaf(
        ctx: Context<InsertLeaf>,
        previous_leaf: [u8; 32],
        insert_value: [u8; 32],
        previous_leaf_path: Vec<[u8; 32]>,
    ) -> Result<u32> {
        let empheral_merkle_tree = &mut ctx.accounts.empheral_merkle_tree;
        
        require!(empheral_merkle_tree.tree_stopped == 0, ErrorCode::TreeStopped);
        require!(
            empheral_merkle_tree.current_index + 1 != 2u32.pow(empheral_merkle_tree.levels),
            ErrorCode::TreeFull
        );
        require!(
            previous_leaf_path.len() == empheral_merkle_tree.levels as usize,
            ErrorCode::InvalidPathLength
        );
        
        let divergence_level = find_divergence_level_for_next(empheral_merkle_tree.current_index, empheral_merkle_tree.levels);
        let new_value_leaf_hash = efficient_hash(insert_value, ctx.accounts.payer.key().to_bytes());
        let new_index = empheral_merkle_tree.current_index + 1;
        
        let mut current_value_leaf = previous_leaf;
        let mut new_path_hash;
        
        for i in 0..empheral_merkle_tree.levels {
            if i == divergence_level {
                new_path_hash = current_value_leaf;
            } else {
                new_path_hash = previous_leaf_path[i as usize];
            }
            
            if ((empheral_merkle_tree.current_index & (1 << i)) >> i) == 0 {
                current_value_leaf = efficient_hash(current_value_leaf, previous_leaf_path[i as usize]);
            } else {
                current_value_leaf = efficient_hash(previous_leaf_path[i as usize], current_value_leaf);
                if i < divergence_level {
                    new_path_hash = zeros(i);
                }
            }
            
        let _new_value_leaf_hash = if ((new_index & (1 << i)) >> i) == 1 {
            efficient_hash(new_path_hash, new_value_leaf_hash)
        } else {
            efficient_hash(new_value_leaf_hash, new_path_hash)
        };
        }
        
        require!(
            current_value_leaf == empheral_merkle_tree.merkle_roots[empheral_merkle_tree.current_index as usize % ROOT_HISTORY_SIZE as usize],
            ErrorCode::ValueLeafMismatch
        );
        
        let current_index = empheral_merkle_tree.current_index;
        empheral_merkle_tree.current_index += 1;
        empheral_merkle_tree.merkle_roots[current_index as usize % ROOT_HISTORY_SIZE as usize] = new_value_leaf_hash;
        
        Ok(empheral_merkle_tree.current_index)
    }

    pub fn stop_tree(ctx: Context<StopTree>) -> Result<()> {
        let empheral_merkle_tree = &mut ctx.accounts.empheral_merkle_tree;
        empheral_merkle_tree.tree_stopped = Clock::get()?.unix_timestamp as u64;
        Ok(())
    }

    pub fn is_known_value_root(
        ctx: Context<IsKnownValueRoot>,
        root: [u8; 32],
    ) -> Result<bool> {
        let empheral_merkle_tree = &ctx.accounts.empheral_merkle_tree;
        
        if root == empheral_merkle_tree.merkle_roots[empheral_merkle_tree.current_index as usize % ROOT_HISTORY_SIZE as usize] {
            return Ok(true);
        }
        
        for i in (0..ROOT_HISTORY_SIZE).rev() {
            if root == empheral_merkle_tree.merkle_roots[i as usize] {
                return Ok(true);
            }
        }
        
        Ok(false)
    }

    pub fn get_last_merkle_root(
        ctx: Context<GetLastMerkleRoot>,
    ) -> Result<[u8; 32]> {
        let empheral_merkle_tree = &ctx.accounts.empheral_merkle_tree;
        Ok(empheral_merkle_tree.merkle_roots[empheral_merkle_tree.current_index as usize % ROOT_HISTORY_SIZE as usize])
    }
}

fn find_divergence_level_for_next(current: u32, levels: u32) -> u32 {
    let next = current + 1;
    let lowest_bit = next & (!next + 1);
    
    for i in 0..levels {
        if lowest_bit == (1 << i) {
            return i;
        }
    }
    levels
}

fn efficient_hash(a: [u8; 32], b: [u8; 32]) -> [u8; 32] {
    let mut input = Vec::new();
    input.extend_from_slice(&a);
    input.extend_from_slice(&b);
    let mut hash = [0u8; 32];
    let mut hasher = Keccak::v256();
    hasher.update(&input);
    hasher.finalize(&mut hash);
    hash
}

